/** نرمال‌سازی متن فارسی برای تطبیق کلیدواژه */
function normalize(t) {
  return String(t || "")
    .replace(/[ي]/g, "ی")
    .replace(/[ك]/g, "ک")
    .replace(/[۰-۹]/g, (d) => "۰۱۲۳۴۵۶۷۸۹".indexOf(d))
    .replace(/[^\u0600-\u06FFa-zA-Z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

/**
 * موتور اصلی: پیام کاربر را می‌گیرد و بهترین گره را پیدا می‌کند
 * خروجی سازگار با API واقعی: { answer, source, confidence, branch, route }
 */
function processMessage(message) {
  const q = normalize(message);
  if (!q) {
    return {
      answer: "پیامی دریافت نشد. لطفاً سؤال خود را بنویسید.",
      source: "مدیریت ابهام",
      confidence: 40,
      branch: "CHAT",
      route: "clarify"
    };
  }

  let best = null;
  let bestScore = 0;
  let bestBranch = null;
  let bestNodeKey = null;

  for (const [branchId, branch] of Object.entries(TREE)) {
    for (const [nodeKey, node] of Object.entries(branch.nodes)) {
      let score = 0;
      for (const kw of node.keywords) {
        const k = normalize(kw);
        if (!k) continue;
        if (q.includes(k)) score += k.length >= 4 ? 3 : 2;
        // تطبیق واژه‌به‌واژه
        const parts = k.split(" ");
        for (const p of parts) {
          if (p.length >= 2 && q.split(" ").includes(p)) score += 1;
        }
      }
      if (score > bestScore) {
        bestScore = score;
        best = node;
        bestBranch = branchId;
        bestNodeKey = nodeKey;
      }
    }
  }

  if (best && bestScore >= 2) {
    return {
      answer: best.answer,
      source: "هسته درخت دانش",
      confidence: Math.min(99, best.conf + Math.min(bestScore, 5)),
      branch: TREE[bestBranch].name,
      route: "tree"
    };
  }

  // ابهام / عدم تطبیق
  const suggestions = [
    "درخشا چیست؟",
    "درخت دانش چیست؟",
    "سازندگان کیانند؟",
    "قابلیت‌های درخشا چیست؟"
  ];
  return {
    answer:
      "این پرسش هنوز گره مشخصی در درخت دانش ندارد.\n\nمی‌توانید یکی از این‌ها را بپرسید:\n• " +
      suggestions.join("\n• ") +
      "\n\nیا موضوع را دقیق‌تر بنویسید تا شاخه مرتبط فعال شود.",
    source: "مدیریت ابهام",
    confidence: 45,
    branch: "CHAT",
    route: "clarify"
  };
}

/** شبیه‌سازی تأخیر شبکه برای حس واقعی‌تر */
function delay(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

/**
 * نقطه ورود واحد: اگر API واقعی تنظیم شده باشد از سرور می‌گیرد،
 * وگرنه از موتور محلی استفاده می‌کند.
 */
async function chat(message, sessionId) {
  const API = window.DERAKHSHA_API || "";
  if (API) {
    const res = await fetch(API + "/api/chat", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ message, session_id: sessionId })
    });
    if (!res.ok) throw new Error("API error " + res.status);
    return await res.json();
  }
  // موتور محلی
  await delay(400 + Math.random() * 500);
  return processMessage(message);
}
